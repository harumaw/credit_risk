def reason_text(code: str) -> str:
    return REASONS.get(code, (code, ""))[0]


def hints(codes: list[str]) -> list[str]:
    """Подсказки по кодам причин, без повторов, в порядке важности причин."""
    seen: list[str] = []
    for code in codes:
        hint = REASONS.get(code, ("", ""))[1]
        if hint and hint not in seen:
            seen.append(hint)
    return seen
